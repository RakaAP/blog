CREATE TABLE IF NOT EXISTS researches (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    profile_id BIGINT NOT NULL,
    year VARCHAR(20) NOT NULL,
    journal_name VARCHAR(255) NOT NULL,
    title VARCHAR(500) NOT NULL,
    summary TEXT NOT NULL,
    researchers VARCHAR(500) NOT NULL,
    doi VARCHAR(255),
    publication_url VARCHAR(500),
    display_order INT DEFAULT 0,
    created_at TIMESTAMP(6) WITHOUT TIME ZONE DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP(6) WITHOUT TIME ZONE DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_researches_profile FOREIGN KEY (profile_id) REFERENCES profiles(id) ON DELETE CASCADE
);

CREATE INDEX IF NOT EXISTS idx_researches_profile_id ON researches(profile_id);
