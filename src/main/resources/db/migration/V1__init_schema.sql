-- Inisialisasi skema basis data PostgreSQL untuk Personal Blog & CMS Engine
-- Idempotent: Menggunakan IF NOT EXISTS untuk kompatibilitas cold start
-- =============================================================================

-- 1. Tabel Users (Manajemen Autentikasi Admin & Role)
CREATE TABLE IF NOT EXISTS users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username VARCHAR(100) NOT NULL,
    password VARCHAR(255) NOT NULL,
    display_name VARCHAR(150),
    role VARCHAR(50) NOT NULL DEFAULT 'ROLE_ADMIN',
    created_at TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP(6) WITHOUT TIME ZONE,
    CONSTRAINT uk_users_username UNIQUE (username)
);

-- 2. Tabel Author Profile (Profil Penulis, Bio, Highlight & Metadata)
CREATE TABLE IF NOT EXISTS author_profile (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(255) NOT NULL,
    full_name VARCHAR(255) NOT NULL,
    role VARCHAR(255) NOT NULL,
    headline VARCHAR(255) NOT NULL,
    bio TEXT NOT NULL,
    avatar_url VARCHAR(1000),
    location VARCHAR(255),
    experience VARCHAR(255),
    specialization VARCHAR(255),
    status VARCHAR(255),
    availability VARCHAR(255),
    github_url VARCHAR(255),
    linkedin_url VARCHAR(255),
    email VARCHAR(255),
    internal_notes TEXT,
    highlights_json TEXT,
    updated_at TIMESTAMP(6) WITHOUT TIME ZONE
);

-- 3. Tabel Site Settings (Konfigurasi Dinamis Key-Value Global)
CREATE TABLE IF NOT EXISTS site_settings (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    config_key VARCHAR(100) NOT NULL,
    config_value TEXT,
    description VARCHAR(255),
    updated_at TIMESTAMP(6) WITHOUT TIME ZONE DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uk_site_settings_config_key UNIQUE (config_key)
);

-- 4. Tabel Posts (Artikel & Konten Blog)
CREATE TABLE IF NOT EXISTS posts (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title VARCHAR(200) NOT NULL,
    content TEXT NOT NULL,
    summary TEXT,
    slug VARCHAR(200),
    author VARCHAR(100),
    category VARCHAR(50),
    read_time VARCHAR(50),
    created_at TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP(6) WITHOUT TIME ZONE
);

-- 5. Tabel Projects (Software Projects & Publikasi Riset Ilmiah)
CREATE TABLE IF NOT EXISTS projects (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title VARCHAR(200) NOT NULL,
    type VARCHAR(50) NOT NULL,
    category VARCHAR(100),
    description TEXT NOT NULL,
    details TEXT,
    tags VARCHAR(250),
    demo_url VARCHAR(250),
    repo_url VARCHAR(250),
    venue VARCHAR(150),
    doi VARCHAR(100),
    created_at TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- 6. Tabel Careers (Riwayat Pengalaman Kerja & Linimasa Akademik)
CREATE TABLE IF NOT EXISTS careers (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    role VARCHAR(150) NOT NULL,
    company VARCHAR(150) NOT NULL,
    period VARCHAR(80) NOT NULL,
    type VARCHAR(50),
    summary TEXT,
    achievements TEXT,
    skills VARCHAR(250),
    created_at TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- 7. Tabel Comments (Komentar Pengunjung Pada Artikel Blog)
CREATE TABLE IF NOT EXISTS comments (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    post_id BIGINT NOT NULL,
    author_name VARCHAR(100) NOT NULL,
    author_email VARCHAR(150),
    content TEXT NOT NULL,
    created_at TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- 8. Tabel Contact Messages (Pesan Masuk Kontak Pengunjung)
CREATE TABLE IF NOT EXISTS contact_messages (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(100) NOT NULL,
    email VARCHAR(150) NOT NULL,
    subject VARCHAR(200),
    phone VARCHAR(30),
    message TEXT NOT NULL,
    is_read BOOLEAN NOT NULL DEFAULT FALSE,
    created_at TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- Indeks untuk mempercepat pencarian & pemfilteran
CREATE INDEX IF NOT EXISTS idx_posts_category ON posts (category);
CREATE INDEX IF NOT EXISTS idx_posts_created_at ON posts (created_at DESC);
CREATE INDEX IF NOT EXISTS idx_projects_type ON projects (type);
CREATE INDEX IF NOT EXISTS idx_careers_type ON careers (type);
CREATE INDEX IF NOT EXISTS idx_comments_post_id ON comments (post_id);
