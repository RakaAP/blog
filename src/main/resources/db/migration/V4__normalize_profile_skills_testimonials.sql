-- 1. Migrasi tabel author_profile menjadi profiles
DO $$
BEGIN
    IF EXISTS (SELECT 1 FROM information_schema.tables WHERE table_name = 'author_profile' AND table_type = 'BASE TABLE') 
       AND NOT EXISTS (SELECT 1 FROM information_schema.tables WHERE table_name = 'profiles' AND table_type = 'BASE TABLE') THEN
        ALTER TABLE author_profile RENAME TO profiles;
    END IF;
END $$;

CREATE TABLE IF NOT EXISTS profiles (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(255) NOT NULL,
    full_name VARCHAR(255) NOT NULL,
    role VARCHAR(255) NOT NULL,
    headline VARCHAR(255) NOT NULL,
    bio TEXT NOT NULL,
    avatar_url VARCHAR(1000),
    location VARCHAR(255),
    experience VARCHAR(255),
    specialization VARCHAR(255),
    status VARCHAR(255),
    availability VARCHAR(255),
    github_url VARCHAR(255),
    linkedin_url VARCHAR(255),
    email VARCHAR(255),
    phone VARCHAR(50),
    cv_url VARCHAR(500),
    internal_notes TEXT,
    highlights_json TEXT,
    skills_json TEXT,
    testimonial_json TEXT,
    updated_at TIMESTAMP(6) WITHOUT TIME ZONE DEFAULT CURRENT_TIMESTAMP
);

-- Buat view author_profile untuk backward-compatibility jika ada query legacy
CREATE OR REPLACE VIEW author_profile AS SELECT * FROM profiles;

-- 2. Tabel Keahlian (skills) dengan relasi One-to-Many ke profiles
CREATE TABLE IF NOT EXISTS skills (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    profile_id BIGINT NOT NULL,
    name VARCHAR(150) NOT NULL,
    icon VARCHAR(100),
    proficiency INT NOT NULL DEFAULT 85,
    color VARCHAR(50),
    category VARCHAR(100) DEFAULT 'general',
    display_order INT DEFAULT 0,
    created_at TIMESTAMP(6) WITHOUT TIME ZONE DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_skills_profile FOREIGN KEY (profile_id) REFERENCES profiles(id) ON DELETE CASCADE
);

CREATE INDEX IF NOT EXISTS idx_skills_profile_id ON skills(profile_id);

-- 3. Tabel Testimoni (testimonials) dengan relasi One-to-Many ke profiles
CREATE TABLE IF NOT EXISTS testimonials (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    profile_id BIGINT NOT NULL,
    quote TEXT NOT NULL,
    author VARCHAR(150) NOT NULL,
    role VARCHAR(150),
    avatar_url VARCHAR(500),
    display_order INT DEFAULT 0,
    created_at TIMESTAMP(6) WITHOUT TIME ZONE DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_testimonials_profile FOREIGN KEY (profile_id) REFERENCES profiles(id) ON DELETE CASCADE
);

CREATE INDEX IF NOT EXISTS idx_testimonials_profile_id ON testimonials(profile_id);

